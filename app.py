import turtle
from turtle import *
t = Turtle()
def draw_square():
    t.shape('turtle')
    t.forward(200)
    t.left(90)
    t.forward(200)
    t.left(90)
draw_square()
t.forward (200)
t.right (90)
t.forward (200)
t.right (90)
t.forward (20)
t.right (90)
t.forward (20)
t.left (90)
t.forward (160)
t.right (90)
t.forward (200)
t.right (90) 
t.forward (200)
t.right (90)
t.forward (200)

turtle.done()