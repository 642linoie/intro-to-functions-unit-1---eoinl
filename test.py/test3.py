import turtle
from turtle import *
t = Turtle()

t.shape('turtle')
def draw_line():
    t.forward(200)
    t.left(90)
    t.forward(200)
    t.left(90)
    t.forward(200)
    t.left(90)
    t.forward(200)
draw_line()
t.left(90)
t.forward (20)
def draw_square2():
    t.left(90)
    t.forward(180)
    t.right(90)
    t.forward(200)
    t.right(90)
    t.forward(200)
draw_square2()